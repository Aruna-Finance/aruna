#!/usr/bin/env node
// Builds the measurement tables from raw results, so every number in REPORT.md comes from data.
//   node measurement/report.mjs <results-dir>           write <results-dir>/tables.md
//   node measurement/report.mjs <results-dir> --check   fail if REPORT.md does not contain tables.md verbatim
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [dir, flag] = process.argv.slice(2);
if (!dir) {
  console.error("usage: node measurement/report.mjs <results-dir> [--check]");
  process.exit(2);
}
const ZERO = "11111111111111111111111111111111";
const results = readFileSync(join(dir, "results.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
const agg = JSON.parse(readFileSync(join(dir, "aggregate.json"), "utf8"));
const ok = results.filter((r) => r.ok);
const failed = results.filter((r) => !r.ok);
const totalCalls = ok.reduce((s, r) => s + (r.calls ?? 0), 0);

const pct = (n, of) => (of === 0 ? "—" : `${((100 * n) / of).toFixed(1)}%`);
const int = (n) => n.toLocaleString("en-US");
const table = (head, rows) => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
const calls = (pred) => ok.filter(pred).reduce((s, r) => s + (r.calls ?? 0), 0);
const cls = (c) => (r) => r.classification.class === c;
const basis = (b) => (r) => r.classification.evidence.mutabilityBasis === b;

const CLASSES = ["immutable_verified", "local_upgradeable", "global_by_account", "unknown"];
const BASES = [
  ["no_detected_path", "immutable_verified"],
  ["full_access_key", "local_upgradeable"],
  ["upgrade_imports", "local_upgradeable"],
  ["own_code", "local_upgradeable"],
  ["global_owner", "global_by_account"],
  ["undetermined", "unknown"],
];

const e = (r) => r.classification.evidence;
const unknownKinds = [
  ["account does not exist", (r) => cls("unknown")(r) && e(r).monitoredCodeHash === null],
  ["account exists, no contract code", (r) => cls("unknown")(r) && e(r).monitoredCodeHash === ZERO && e(r).codeRef === null],
  ["code present but not fetched or not parseable", (r) => cls("unknown")(r) && e(r).codeRef !== null],
];

const failReasons = new Map();
for (const r of failed) {
  const k = /TOO_MANY_ACCESS_KEYS/.test(r.error) ? "key list larger than RPC returns (TOO_MANY_ACCESS_KEYS)" : /429/.test(r.error) ? "rate limited by every endpoint (HTTP 429)" : "other RPC failure";
  failReasons.set(k, (failReasons.get(k) ?? 0) + 1);
}

const top = [...ok].sort((a, b) => (b.calls ?? 0) - (a.calls ?? 0)).slice(0, 20);
const blockRange = agg.blockRange ? `${int(agg.blockRange.min)}–${int(agg.blockRange.max)}` : "—";

const out = [
  `<!-- generated by measurement/report.mjs from ${dir}; do not edit by hand -->`,
  "",
  `Accounts in input: **${int(agg.total)}**. Classified: **${int(agg.classified)}**. Not classified (read failed): **${int(failed.length)}**. Mainnet blocks read: ${blockRange}.`,
  "",
  "**Class distribution** (share of classified accounts, and share of the function calls they received in the window)",
  "",
  table(
    ["Class", "Accounts", "Share", "Calls received", "Share of calls"],
    CLASSES.map((c) => [`\`${c}\``, int(agg.byClass[c]), pct(agg.byClass[c], agg.classified), int(calls(cls(c))), pct(calls(cls(c)), totalCalls)]),
  ),
  "",
  "**By basis** (why the class holds)",
  "",
  table(
    ["Basis", "Class", "Accounts", "Share", "Share of calls"],
    BASES.map(([b, c]) => [`\`${b}\``, `\`${c}\``, int(agg.byBasis[b]), pct(agg.byBasis[b], agg.classified), pct(calls(basis(b)), totalCalls)]),
  ),
  "",
  "**Headline 1 — invisible to hash-based monitoring:** " +
    `${int(agg.headline1.globalByAccount)} of ${int(agg.headline1.of)} classified accounts (${pct(agg.headline1.globalByAccount, agg.headline1.of)}) are \`global_by_account\`.`,
  "",
  "**Headline 2 — can change under an agent:** " +
    `${int(agg.headline2.canChange)} of ${int(agg.headline2.of)} (${pct(agg.headline2.canChange, agg.headline2.of)}) have a full-access key, a global owner or unpinned own code; ` +
    `${int(agg.headline2.immutableVerified)} (${pct(agg.headline2.immutableVerified, agg.headline2.of)}) are \`immutable_verified\`. ` +
    `Reported separately because it inflates the total: ${int(agg.headline2.upgradeImportsReportedSeparately)} (${pct(agg.headline2.upgradeImportsReportedSeparately, agg.headline2.of)}) have no full-access key but import a scanned host function. ` +
    `${int(agg.headline2.unknown)} are \`unknown\`.`,
  "",
  "**What `unknown` is made of**",
  "",
  table(["Kind", "Accounts", "Calls received"], unknownKinds.map(([k, f]) => [k, int(ok.filter(f).length), int(calls(f))])),
  "",
  "**Not classified**",
  "",
  failed.length === 0 ? "None." : table(["Reason", "Accounts"], [...failReasons].map(([k, v]) => [k, int(v)])),
  "",
  failed.length === 0 ? "" : `Accounts: ${failed.map((r) => `\`${r.accountId}\``).join(", ")}.`,
  "",
  "**The 20 most-called accounts**",
  "",
  table(
    ["Account", "Calls", "Class", "Basis", "Full-access keys"],
    top.map((r) => [`\`${r.accountId}\``, int(r.calls ?? 0), `\`${r.classification.class}\``, `\`${e(r).mutabilityBasis}\``, int(e(r).fullAccessKeyCount)]),
  ),
  "",
  "**Every `immutable_verified` and `global_by_account` account**",
  "",
  table(
    ["Account", "Class", "Code reference", "Calls"],
    ok
      .filter((r) => cls("immutable_verified")(r) || cls("global_by_account")(r))
      .map((r) => {
        const ref = e(r).codeRef;
        const refText = ref.kind === "global_hash" ? `by hash \`${ref.globalHash}\`` : ref.kind === "global_account" ? `by account \`${ref.ownerAccount}\`` : `local \`${ref.codeHash}\``;
        return [`\`${r.accountId}\``, `\`${r.classification.class}\``, refText, int(r.calls ?? 0)];
      }),
  ),
  "",
].join("\n");

if (flag === "--check") {
  const report = readFileSync(new URL("./REPORT.md", import.meta.url), "utf8");
  if (!report.includes(out.trim())) {
    console.error("REPORT.md does not contain the generated tables verbatim. Re-run without --check and paste tables.md in.");
    process.exit(1);
  }
  console.log("REPORT.md matches the results.");
} else {
  writeFileSync(join(dir, "tables.md"), out);
  console.log(`wrote ${join(dir, "tables.md")}`);
}
